# =============================================================================
# WGCNA network metrics
# =============================================================================

#' Calculate WGCNA Network Metrics
#'
#' @description
#'   Calculates gene-level and module-level connectivity metrics from an
#'   existing WGCNA network. Metrics include module membership (kME),
#'   intramodular connectivity (kWithin), and connectivity to genes outside the
#'   assigned module (kOut and kTotal).
#'
#'   The function calculates metrics for the global network and can optionally
#'   perform additional group-specific evaluations using the same globally
#'   defined modules. Group-specific evaluations recalculate connectivity and
#'   module membership within each selected group without reconstructing the
#'   network or redefining module assignments.
#'
#' @param project An \code{rna_project} object containing a previously
#'   constructed WGCNA network result, generated by \code{\link{rna_wgcna}}.
#'
#' @param group Character vector specifying one or more metadata groups for
#'   group-specific metric evaluation. If \code{NULL}, only global network
#'   metrics are calculated. If one or more groups are supplied, global metrics
#'   are calculated alongside the corresponding group-specific evaluations.
#'   Each selected group must contain at least three samples. Defaults to
#'   \code{NULL}.
#'
#' @param save Logical. If \code{TRUE}, attaches the metrics result to the
#'   project under the \code{analyses} slot with subtype \code{"wgcna_metrics"}
#'   and invisibly returns the updated project. If \code{FALSE}, does not attach
#'   the result and instead invisibly returns an object of class
#'   \code{wgcna_metrics_result}. Defaults to \code{TRUE}.
#'
#' @details
#'   The following metrics are calculated for each gene:
#'   \describe{
#'     \item{kME (module membership)}{
#'       Pearson correlation between gene expression and the eigengene of its
#'       assigned module. The correlation method used during network
#'       construction is retained for consistency.
#'     }
#'     \item{kWithin (intramodular connectivity)}{
#'       Sum of adjacency values between a gene and the other genes belonging
#'       to the same module.
#'     }
#'     \item{kOut (extramodular connectivity)}{
#'       Sum of adjacency values between a gene and genes belonging to other
#'       modules.
#'     }
#'     \item{kTotal (total connectivity)}{
#'       Sum of intramodular and extramodular connectivity
#'       (\code{kWithin + kOut}).
#'     }
#'   }
#'
#'   Module-level summaries include the number of genes assigned to each module
#'   and the mean and median values of kME and kWithin. Unassigned genes
#'   (grey module) are excluded from module-level summaries. Their kME values
#'   are returned as \code{NA}, since they do not belong to a defined module
#'   eigengene.
#'
#'   When group-specific evaluation is requested, the original global module
#'   assignments and eigengenes are retained as the reference. Gene expression
#'   and adjacency values are evaluated using only samples belonging to each
#'   selected group. Consequently, kME represents the correlation with the
#'   corresponding global module eigengene evaluated within the selected group,
#'   while connectivity metrics are recalculated using the group's expression
#'   data.
#'
#'   Group-specific metrics describe connectivity patterns within each group and
#'   should not be interpreted as formal statistical tests of differences
#'   between networks. Differences in connectivity may also reflect differences
#'   in sample size and expression variability.
#'
#' @return
#'   If \code{save = TRUE}, invisibly returns the updated
#'   \code{rna_project} object.
#'
#'   If \code{save = FALSE}, invisibly returns an object of class
#'   \code{wgcna_metrics_result}, containing:
#'   \describe{
#'     \item{gene_metrics}{Data frame containing gene-level metrics for the
#'       global network, including gene identifiers, module assignments, kME,
#'       kWithin, kOut, and kTotal.}
#'     \item{module_summary}{Data frame containing module-level summaries for
#'       the global network.}
#'     \item{by_group}{Named list containing gene-level metrics, module-level
#'       summaries, and sample counts for each selected group. Empty when no
#'       group-specific evaluation is requested.}
#'     \item{parameters}{List containing the correlation method,
#'       soft-thresholding power, network type, and selected groups used in the
#'       evaluation.}
#'     \item{timestamp}{Date and time at which the metrics were calculated.}
#'   }
#'
#' @seealso
#'   \code{\link{rna_wgcna}},
#'   \code{\link{rna_pick_power}}
#'
#' @export

rna_wgcna_metrics <- function(
    project,
    group = NULL,
    save = TRUE
) {

# =============================================================================
# 0. Basic checks
# =============================================================================

.check_dependencies("WGCNA")

# project
if (!inherits(project, "rna_project")) {
  stop("`project` must be an object of class 'rna_project'.")
}

# group
if (!is.null(group)) {
  if (!is.character(group) ||
      length(group) == 0L ||
      anyNA(group) ||
      any(!nzchar(trimws(group)))) {
    stop("`group` must be NULL or a non-empty character vector without missing
         or empty values.")
  }

  group <- unique(group)
}

# save
if (!is.logical(save) || length(save) != 1L || is.na(save)) {
  stop("`save` must be TRUE or FALSE.")
}

# =============================================================================
# 1. Get active project and WGCNA results
# =============================================================================

proj <- project

wgcna_obj <- .get_wgcna(proj)

if (!inherits(wgcna_obj, "wgcna_network_result")) {
  stop("Invalid WGCNA network result.", call. = FALSE)
}

datExpr <- wgcna_obj$datExpr
net <- wgcna_obj$network
MEs <- wgcna_obj$MEs

# =============================================================================
# 2. Calculate global metrics
# =============================================================================

global_metrics <- .calculate_wgcna_metrics(
  datExpr = datExpr,
  MEs = MEs,
  wgcna_obj = wgcna_obj
)

# =============================================================================
# 3. Calculate group-specific metrics
# =============================================================================

by_group <- list()

if (!is.null(group)) {

  for (g in unique(group)) {

    group_data <- .get_wgcna_group_data(
      project = proj,
      wgcna_obj = wgcna_obj,
      group = g
    )

    group_metrics <- .calculate_wgcna_metrics(
      datExpr = group_data$datExpr,
      MEs = group_data$MEs,
      wgcna_obj = wgcna_obj
    )

    by_group[[g]] <- c(
      group_metrics,
      list(
        n_samples = group_data$n_samples
      )
    )
  }
}

# =============================================================================
# 4. Build result object
# =============================================================================

obj <- list(
  gene_metrics = global_metrics$gene_metrics,
  module_summary = global_metrics$module_summary,
  by_group = by_group,
  parameters = list(
    cor_method = wgcna_obj$cor_method,
    power = wgcna_obj$power,
    network_type = wgcna_obj$network_type,
    groups = group
  ),
  timestamp = Sys.time()
)

class(obj) <- "wgcna_metrics_result"

# =============================================================================
# 5. Console summary
# =============================================================================

.print_header("WGCNA Metrics Results")

.print_block("Network Summary", function() {
  cat("Correlation method:   ", obj$parameters$cor_method, "\n")
  cat("Network type:         ", obj$parameters$network_type, "\n")
  cat("Soft-threshold power: ", obj$parameters$power, "\n")
})

# Metrics summary
.print_block("Metrics Summary", function() {

  if (is.null(group)) {

    cat("Evaluation:            Global network\n")

    metrics <- global_metrics

  } else if (length(group) == 1) {

    cat("Evaluation:            Group - ", group, "\n", sep = "")

    metrics <- by_group[[group]]

  } else {

    cat("Evaluation:            Global network\n")

    metrics <- global_metrics
  }

  n_genes <- nrow(metrics$gene_metrics)

  n_grey <- sum(
    metrics$gene_metrics$ModuleColor == "grey",
    na.rm = TRUE
  )

  cat("Genes evaluated:      ", n_genes, "\n")
  cat("Genes assigned:       ", n_genes - n_grey, "\n")
  cat("Unassigned genes:     ", n_grey, "\n")
  cat("Modules identified:   ", nrow(metrics$module_summary), "\n")
})

# Group-specific evaluations
if (length(by_group) > 1) {

  .print_block("Group-specific Evaluations", function() {

    groups <- names(by_group)

    for (i in seq_along(groups)) {

      g <- groups[i]

      cat("Group:                 ", g, "\n", sep = "")
      cat("Samples:              ", by_group[[g]]$n_samples, "\n")
      cat("Genes evaluated:      ", nrow(by_group[[g]]$gene_metrics), "\n")
      cat("Modules evaluated:    ", nrow(by_group[[g]]$module_summary), "\n")

      # Add spacing only between groups
      if (i < length(groups)) {
        cat("\n")
      }
    }
  })
}

# Module summary
if (is.null(group) || length(group) == 1) {

  module_data <- if (is.null(group)) {
    global_metrics
  } else {
    by_group[[group]]
  }

  .print_block("Module Summary", function() {

    print(
      module_data$module_summary[, c(
        "Module",
        "ModuleColor",
        "NGenes",
        "Mean_kME",
        "Median_kME",
        "Mean_kWithin",
        "Median_kWithin"
      )],
      row.names = FALSE
    )
  })
}

# =============================================================================
# 6. Attach to project
# =============================================================================

if (save) {

  proj <- .attach_to_project(
    proj,
    obj,
    slot = "analyses",
    subtype = "wgcna_metrics"
  )

  return(invisible(proj))

}

return(invisible(obj))
}


