# =============================================================================
# RNA WGCNA STABILITY
# =============================================================================

#' Evaluate WGCNA module preservation and network stability
#'
#' @description
#'   Evaluates the preservation of co-expression modules, the stability of
#'   module membership (kME), and the conservation of intramodular hub genes
#'   between two experimental groups using independently reconstructed WGCNA
#'   networks.
#'
#'   Networks are reconstructed using the original WGCNA configuration stored
#'   in the project. Module preservation is assessed using permutation-based
#'   statistics, while kME correlations and hub gene overlap provide
#'   complementary measures of network stability. All comparisons are performed
#'   bidirectionally, using each group as the reference network.
#'
#' @param project An \code{rna_project} object containing a previously
#'   constructed WGCNA network generated by \code{\link{rna_wgcna}}.
#'
#' @param group Optional character vector specifying exactly two experimental
#'   groups to compare. Both groups must be represented among the samples used
#'   in the original network. If \code{NULL}, groups are automatically
#'   identified when exactly two are available. Defaults to \code{NULL}.
#'
#' @param reference Optional character string specifying the reference group.
#'   The other selected group is automatically assigned as the comparison
#'   group. If \code{NULL}, the first selected group is used. Defaults to
#'   \code{NULL}.
#'
#' @param n_permutations Integer specifying the number of permutations used
#'   for module preservation analysis. Larger values provide more stable
#'   estimates but increase computational requirements. Defaults to
#'   \code{200}.
#'
#' @param hub_quantile Numeric value between 0 and 1 defining the quantile
#'   used to identify hub genes based on absolute kME values. For example,
#'   \code{0.90} selects approximately the top 10\% of genes within each
#'   module. Defaults to \code{0.90}.
#'
#' @param threads Optional positive integer specifying the number of threads
#'   used during network reconstruction. If \code{NULL}, the default WGCNA
#'   behavior is used. Defaults to \code{NULL}.
#'
#' @param plot Logical. If \code{TRUE}, generates a bar plot of module
#'   preservation Zsummary statistics, including conventional preservation
#'   thresholds. Defaults to \code{TRUE}.
#'
#' @param save Logical. If \code{TRUE}, attaches the analysis result to the
#'   project under \code{analyses$wgcna_stability} and invisibly returns the
#'   updated project. Otherwise, invisibly returns an object of class
#'   \code{wgcna_stability_result}. Defaults to \code{TRUE}.
#'
#' @section Input requirements:
#'   The original WGCNA result must contain the expression matrix and network
#'   configuration required for independent network reconstruction.
#'
#'   Sample metadata must contain unique \code{Sample} identifiers and a
#'   \code{Group} column. Sample identifiers must match the expression matrix
#'   row names. Metadata are automatically aligned to the expression matrix,
#'   and only samples included in the original network are considered.
#'
#'   Missing or empty group assignments are not allowed, and each selected
#'   group must contain at least 20 samples. The original set of WGCNA genes
#'   is retained without additional filtering.
#'
#' @section Analysis:
#'   Independent networks are reconstructed for each selected group using
#'   the original WGCNA configuration. Module assignments may therefore
#'   differ between groups.
#'
#'   Three complementary stability measures are evaluated:
#'
#' \itemize{
#'   \item \strong{Module preservation:} assessed using
#'   \code{\link[WGCNA]{modulePreservation}}, which evaluates the conservation
#'   of module topology between reference and comparison networks. Zsummary
#'   values below 2 indicate weak evidence of preservation, values between 2 and
#'   10 indicate moderate evidence, and values above 10 indicate strong
#'   evidence. These thresholds are empirical guidelines rather than formal
#'   significance cutoffs.
#'
#'   \item \strong{Module membership stability:} evaluated using Pearson
#'   correlations between gene-level kME values calculated relative to reference
#'   module eigengenes in both groups. Higher correlations indicate greater
#'   conservation of gene-module relationships.
#'
#'   \item \strong{Hub gene stability:} assessed by comparing the genes with the
#'   highest absolute kME values in each reference module. Hub overlap and the
#'   Jaccard index quantify the conservation of selected hub genes between
#'   groups.
#'   }
#'
#'   All analyses are performed bidirectionally, using each group as the
#'   reference in turn. Grey modules are excluded from the interpretable
#'   preservation summary but retained in the raw WGCNA output.
#'
#' @section Interpretation:
#'   Module preservation, kME stability, and hub overlap describe different
#'   aspects of network organization. A module may retain its overall topology
#'   while exhibiting changes in gene-module relationships or hub identity.
#'   Conversely, conserved hub genes do not necessarily indicate preservation of
#'   the entire module structure.
#'
#'   These measures do not establish network identity, exclude differential
#'   co-expression, or demonstrate causal relationships. Results should be
#'   interpreted in the context of sample size, experimental design, and
#'   potential confounding factors.
#'
#'   The function performs pairwise comparisons and does not implement formal
#'   differential network analysis, consensus network construction, or
#'   statistical adjustment for experimental covariates and repeated
#'   measurements.
#'
#' @return
#'   If \code{save = TRUE}, invisibly returns the updated
#'   \code{rna_project} object.
#'
#'   If \code{save = FALSE}, invisibly returns an object of class
#'   \code{wgcna_stability_result}, containing:
#'   \itemize{
#'     \item \code{preservation}: interpretable module preservation
#'     statistics for both comparison directions.
#'     \item \code{preservation_raw}: complete output from
#'     \code{\link[WGCNA]{modulePreservation}}, including permutation results.
#'     \item \code{kME_stability}: gene-module membership correlations
#'     and associated comparison information.
#'     \item \code{hub_stability}: hub overlap, Jaccard indices, and
#'     associated module statistics.
#'     \item \code{networks}: independently reconstructed WGCNA networks,
#'     including module assignments and eigengenes.
#'     \item \code{parameters}: selected groups, sample counts, network
#'     configuration, and analysis parameters.
#'     \item \code{timestamp}: date and time of analysis.
#'   }
#'
#' @seealso
#'   \code{\link{rna_wgcna}},
#'   \code{\link{rna_wgcna_metrics}},
#'   \code{\link{rna_wgcna_module_trait}},
#'   \code{\link[WGCNA]{modulePreservation}},
#'   \code{\link[WGCNA]{moduleEigengenes}}
#'
#' @references
#'   Langfelder P, Horvath S. (2008).
#'   WGCNA: an R package for weighted correlation network analysis.
#'   \emph{BMC Bioinformatics}, 9, 559.
#'   \doi{10.1186/1471-2105-9-559}
#'
#'   Langfelder P, Luo R, Oldham MC, Horvath S. (2011).
#'   Is my network module preserved and reproducible?
#'   \emph{PLoS Computational Biology}, 7(1), e1001057.
#'   \doi{10.1371/journal.pcbi.1001057}
#'
#' @export

rna_wgcna_stability <- function(
    project,
    group = NULL,
    reference = NULL,
    n_permutations = 200,
    hub_quantile = 0.90,
    threads = NULL,
    plot = TRUE,
    save = TRUE
) {

# =============================================================================
# 1. Dependencies and input validation
# =============================================================================

.check_dependencies("WGCNA")

# project
if (!inherits(project, "rna_project")) {
  stop("'project' must be an rna_project object.")
}

# group
if (!is.null(group)) {

  if (!is.character(group) ||
      length(group) == 0L ||
      anyNA(group) ||
      any(!nzchar(trimws(group)))) {
    stop(
      "`group` must be NULL or a non-empty character vector ",
      "without missing or empty values."
    )
  }

  group <- unique(group)

  if (length(group) != 2L) {
    stop(
      "`group` must identify exactly two distinct experimental groups."
    )
  }
}

# n_permutations
if (!is.numeric(n_permutations) ||
    length(n_permutations) != 1 ||
    is.na(n_permutations) ||
    !is.finite(n_permutations) ||
    n_permutations < 1 ||
    n_permutations != as.integer(n_permutations)) {
  stop("'n_permutations' must be a positive integer.")
}

# hub_quantile
if (!is.numeric(hub_quantile) ||
    length(hub_quantile) != 1 ||
    is.na(hub_quantile) ||
    !is.finite(hub_quantile) ||
    hub_quantile <= 0 ||
    hub_quantile >= 1) {
  stop("'hub_quantile' must be between 0 and 1.")
}

# threads
if (!is.null(threads) &&
    (!is.numeric(threads) ||
     length(threads) != 1 ||
     is.na(threads) ||
     !is.finite(threads) ||
     threads < 1 ||
     threads != as.integer(threads))) {
  stop("'threads' must be NULL or a positive integer.")
}

# plpt
if (!is.logical(plot) || length(plot) != 1 || is.na(plot)) {
  stop("'plot' must be TRUE or FALSE.")
}

# save
if (!is.logical(save) || length(save) != 1 || is.na(save)) {
  stop("'save' must be TRUE or FALSE.")
}

# =============================================================================
# 2. Retrieve and validate original WGCNA network
# =============================================================================

proj <- project

wgcna_obj <- .get_wgcna(proj)

if (!inherits(wgcna_obj, "wgcna_network_result")) {
  stop("No valid WGCNA network was found in the project.")
}

# Parameters required to reproduce the original network configuration.
required_parameters <- c(
  "power",
  "network_type",
  "tom_type",
  "cor_method",
  "max_block_size",
  "min_module_size",
  "deep_split",
  "reassign_threshold",
  "merge_cut_height",
  "numeric_labels",
  "pam_respects_dendro"
)

missing_parameters <- required_parameters[
  !vapply(
    required_parameters,
    function(x) !is.null(wgcna_obj[[x]]),
    logical(1)
  )
]

if (length(missing_parameters) > 0) {
  stop(
    "The stored WGCNA network is missing required parameters: ",
    paste(missing_parameters, collapse = ", "),
    ". Please rebuild the original network using the updated ",
    "'rna_wgcna()' function before running stability analysis."
  )
}

datExpr <- wgcna_obj$datExpr

if (is.null(datExpr) ||
    (!is.matrix(datExpr) && !is.data.frame(datExpr))) {
  stop("The original expression matrix is missing or invalid.")
}

datExpr <- as.matrix(datExpr)

if (!is.numeric(datExpr)) {
  stop("The original expression matrix must contain numeric values.")
}

if (is.null(rownames(datExpr)) ||
    is.null(colnames(datExpr))) {
  stop("Expression matrix must contain sample and gene identifiers.")
}

if (anyDuplicated(rownames(datExpr)) ||
    anyDuplicated(colnames(datExpr))) {
  stop("Expression matrix contains duplicated sample or gene identifiers.")
}

# =============================================================================
# 3. Align metadata and expression data
# =============================================================================

metadata <- .get_meta(proj)

if (!is.data.frame(metadata) ||
    !all(c("Sample", "Group") %in% colnames(metadata))) {
  stop("Metadata must contain 'Sample' and 'Group' columns.")
}

if (anyNA(metadata$Sample) ||
    anyDuplicated(metadata$Sample)) {
  stop("Metadata contains missing or duplicated sample identifiers.")
}

sample_idx <- match(
  rownames(datExpr),
  as.character(metadata$Sample)
)

if (anyNA(sample_idx)) {
  stop("Some WGCNA samples could not be matched to metadata.")
}

sample_groups <- as.character(
  metadata$Group[sample_idx]
)

if (anyNA(sample_groups) ||
    any(!nzchar(trimws(sample_groups)))) {
  stop(
    "Some WGCNA samples have missing or empty group assignments ",
    "in the project metadata."
  )
}

# ===============================================
# 3.1. Identify experimental groups
# ===============================================

available_groups <- unique(sample_groups)

if (is.null(group)) {

  if (length(available_groups) != 2L) {
    stop(
      "Automatic group selection requires exactly two experimental ",
      "groups among the samples used in the original WGCNA network. ",
      "Detected: ",
      paste(available_groups, collapse = ", "),
      ". Please specify the two groups using the 'group' argument."
    )
  }

  group <- available_groups

  message(
    "Automatically detected experimental groups: ",
    paste(group, collapse = " and ")
  )

} else {

  missing_groups <- setdiff(group, available_groups)

  if (length(missing_groups) > 0L) {
    stop(
      "The following selected groups are not present among the ",
      "samples used in the original WGCNA network: ",
      paste(missing_groups, collapse = ", "),
      "."
    )
  }
}

# ===============================================
# 3.2. Validate reference group
# ===============================================

if (!is.null(reference) &&
    (!is.character(reference) ||
     length(reference) != 1L ||
     is.na(reference) ||
     !nzchar(trimws(reference)))) {
  stop("'reference' must be a single non-empty group name.")
}

if (!is.null(reference) && !reference %in% group) {
  stop("'reference' must be one of the selected groups.")
}

if (is.null(reference)) {
  reference <- group[1]
}

comparison <- setdiff(group, reference)

# =============================================================================
# 4. Split expression data
# =============================================================================

datExpr_reference <- datExpr[
  sample_groups == reference,
  ,
  drop = FALSE
]

datExpr_comparison <- datExpr[
  sample_groups == comparison,
  ,
  drop = FALSE
]

n_reference <- nrow(datExpr_reference)
n_comparison <- nrow(datExpr_comparison)

if (n_reference < 20 || n_comparison < 20) {
  stop(
    "At least 20 samples per group are required for this analysis. ",
    "Observed: ", reference, " = ", n_reference,
    "; ", comparison, " = ", n_comparison, "."
  )
}

message(
  "Building independent networks: ",
  reference, " (n = ", n_reference, ") and ",
  comparison, " (n = ", n_comparison, ")."
)

# =============================================================================
# 5. Rebuild independent networks using original parameters
# =============================================================================

network_args <- list(
  power = wgcna_obj$power,
  network_type = wgcna_obj$network_type,
  tom_type = wgcna_obj$tom_type,
  cor_method = wgcna_obj$cor_method,
  max_block_size = wgcna_obj$max_block_size,
  min_module_size = wgcna_obj$min_module_size,
  deep_split = wgcna_obj$deep_split,
  reassign_threshold = wgcna_obj$reassign_threshold,
  merge_cut_height = wgcna_obj$merge_cut_height,
  numeric_labels = wgcna_obj$numeric_labels,
  pam_respects_dendro = wgcna_obj$pam_respects_dendro,
  threads = threads
)

network_reference <- do.call(
  .build_wgcna_group_network,
  c(
    list(datExpr = datExpr_reference),
    network_args
  )
)

network_comparison <- do.call(
  .build_wgcna_group_network,
  c(
    list(datExpr = datExpr_comparison),
    network_args
  )
)

# =============================================================================
# 6. Module preservation analysis
# =============================================================================

multiExpr <- list(
  reference = list(data = datExpr_reference),
  comparison = list(data = datExpr_comparison)
)

names(multiExpr) <- c(reference, comparison)

multiColor <- list(
  reference = network_reference$colors,
  comparison = network_comparison$colors
)

names(multiColor) <- c(reference, comparison)

preservation <- WGCNA::modulePreservation(
  multiData = multiExpr,
  multiColor = multiColor,
  dataIsExpr = TRUE,
  networkType = wgcna_obj$network_type,
  corFnc = "cor",
  corOptions = paste0(
    "use = 'p', method = '",
    wgcna_obj$cor_method,
    "'"
  ),
  referenceNetworks = c(1, 2),
  testNetworks = list(2, 1),
  nPermutations = as.integer(n_permutations),
  randomSeed = 12345,
  maxModuleSize = ncol(datExpr),
  savePermutedStatistics = FALSE,
  parallelCalculation = FALSE,
  verbose = 1
)

# =============================================================================
# 7. Extract preservation statistics
# =============================================================================

z_stats <- preservation$preservation$Z

if (is.null(z_stats) || length(z_stats) == 0) {
  stop("No module preservation statistics were returned by WGCNA.")
}

preservation_summary <- list()

for (direction in list(
  c(reference, comparison),
  c(comparison, reference)
)) {

  ref_name <- direction[1]
  test_name <- direction[2]

  # Locate reference network
  ref_candidates <- c(
    paste0("ref.", ref_name),
    paste0("ref_", ref_name)
  )

  ref_key <- intersect(ref_candidates, names(z_stats))

  if (length(ref_key) == 0) {
    next
  }

  ref_key <- ref_key[1]

  # Locate test network
  test_candidates <- c(
    paste0("inColumnsAlsoPresentIn.", test_name),
    paste0("inColumnsAlsoPresentIn_", test_name)
  )

  test_key <- intersect(
    test_candidates,
    names(z_stats[[ref_key]])
  )

  if (length(test_key) == 0) {
    next
  }

  test_key <- test_key[1]

  stats_table <- as.data.frame(
    z_stats[[ref_key]][[test_key]]
  )

  stats_table$Module <- rownames(stats_table)
  stats_table$Reference <- ref_name
  stats_table$Comparison <- test_name

  preservation_summary[[
    paste(ref_name, test_name, sep = "_vs_")
  ]] <- stats_table
}

if (length(preservation_summary) > 0) {
  preservation_summary <- do.call(
    rbind,
    preservation_summary
  )

  rownames(preservation_summary) <- NULL

} else {
  preservation_summary <- data.frame()
}

# Exclude unassigned genes from the interpretable summary
if (nrow(preservation_summary) > 0) {

  preservation_summary <- preservation_summary[
    !is.na(preservation_summary$Module) &
      !preservation_summary$Module %in% c("grey", "0"),
    ,
    drop = FALSE
  ]

  rownames(preservation_summary) <- NULL
}

# =============================================================================
# 8. Hub stability analysis
# =============================================================================

hub_reference <- .calculate_wgcna_hub_stability(
  datExpr_reference,
  datExpr_comparison,
  network_reference$colors,
  hub_quantile
)

hub_comparison <- .calculate_wgcna_hub_stability(
  datExpr_comparison,
  datExpr_reference,
  network_comparison$colors,
  hub_quantile
)

if (nrow(hub_reference) > 0) {
  hub_reference$Reference <- reference
  hub_reference$Comparison <- comparison
}

if (nrow(hub_comparison) > 0) {
  hub_comparison$Reference <- comparison
  hub_comparison$Comparison <- reference
}

hub_stability <- rbind(
  hub_reference,
  hub_comparison
)

# =============================================================================
# 9. Module membership stability summary
# =============================================================================

kME_columns <- c(
  "Module",
  "Reference",
  "Comparison",
  "N_genes",
  "kME_correlation"
)

if (nrow(hub_stability) > 0) {

  missing_columns <- setdiff(
    kME_columns,
    colnames(hub_stability)
  )

  if (length(missing_columns) > 0) {
    stop(
      "Hub stability results are missing required columns: ",
      paste(missing_columns, collapse = ", ")
    )
  }

  kME_stability <- hub_stability[
    ,
    kME_columns,
    drop = FALSE
  ]

} else {

  kME_stability <- data.frame(
    Module = character(),
    Reference = character(),
    Comparison = character(),
    N_genes = integer(),
    kME_correlation = numeric(),
    stringsAsFactors = FALSE
  )
}

# =============================================================================
# 10. Build result object
# =============================================================================

obj <- list(
  preservation = preservation_summary,
  preservation_raw = preservation,
  kME_stability = kME_stability,
  hub_stability = hub_stability,

  networks = list(
    reference = network_reference,
    comparison = network_comparison
  ),

  parameters = list(
    reference = reference,
    comparison = comparison,
    n_reference = n_reference,
    n_comparison = n_comparison,
    n_genes = ncol(datExpr),
    n_permutations = as.integer(n_permutations),
    hub_quantile = hub_quantile,

    # Original network configuration
    power = wgcna_obj$power,
    genes_n = wgcna_obj$genes_n,
    network_type = wgcna_obj$network_type,
    tom_type = wgcna_obj$tom_type,
    cor_method = wgcna_obj$cor_method,
    max_block_size = wgcna_obj$max_block_size,
    min_module_size = wgcna_obj$min_module_size,
    deep_split = wgcna_obj$deep_split,
    reassign_threshold = wgcna_obj$reassign_threshold,
    merge_cut_height = wgcna_obj$merge_cut_height,
    numeric_labels = wgcna_obj$numeric_labels,
    pam_respects_dendro = wgcna_obj$pam_respects_dendro,

    # Operational parameter
    threads = threads
  ),

  timestamp = Sys.time()
)

class(obj) <- "wgcna_stability_result"

# =============================================================================
# 11. Basic visualization
# =============================================================================

if (plot && nrow(preservation_summary) > 0) {

  z_column <- grep(
    "Zsummary.pres",
    colnames(preservation_summary),
    value = TRUE
  )

  if (length(z_column) > 0) {

    graphics::barplot(
      preservation_summary[[z_column[1]]],
      names.arg = preservation_summary$Module,
      las = 2,
      ylab = "Zsummary preservation",
      main = "Module preservation",
      col = "steelblue"
    )

    graphics::abline(h = 2, lty = 2, col = "orange")
    graphics::abline(h = 10, lty = 2, col = "red")
  }
}


# =============================================================================
# 12. Console summary
# =============================================================================

.print_header("WGCNA Stability Results")

# Network summary
.print_block("Network Summary", function() {

  cat("Reference group:       ", reference, "\n")
  cat("Comparison group:      ", comparison, "\n")
  cat("Reference samples:     ", n_reference, "\n")
  cat("Comparison samples:    ", n_comparison, "\n")
  cat("Genes evaluated:       ", ncol(datExpr), "\n")
  cat("Correlation method:    ", wgcna_obj$cor_method, "\n")
  cat("Network type:          ", wgcna_obj$network_type, "\n")
  cat("Soft-threshold power:  ", wgcna_obj$power, "\n")
  cat("Permutations:          ", n_permutations, "\n")
})

# Preservation summary
.print_block("Module Preservation", function() {

  if (nrow(preservation_summary) == 0) {

    cat("No assigned modules available for preservation summary.\n")

  } else {

    z_column <- grep(
      "^Zsummary\\.pres$",
      colnames(preservation_summary),
      value = TRUE
    )

    if (length(z_column) == 0) {

      cat("Zsummary statistics were not available.\n")

    } else {

      z_values <- preservation_summary[[z_column[1]]]
      valid <- is.finite(z_values)
      z_values <- z_values[valid]

      if (length(z_values) == 0) {

        cat("No valid Zsummary values available.\n")

      } else {

        cat(
          "Modules evaluated:     ",
          length(unique(preservation_summary$Module[valid])),
          "\n"
        )

        cat("Strong preservation:   ", sum(z_values >= 10), "\n")
        cat("Moderate preservation: ", sum(z_values >= 2 & z_values < 10), "\n")
        cat("Weak evidence:         ", sum(z_values < 2), "\n")

        cat(
          "Median Zsummary:       ",
          round(stats::median(z_values), 3),
          "\n"
        )
      }
    }
  }
})

# kME stability summary
.print_block("Module Membership Stability", function() {

  if (nrow(kME_stability) == 0) {

    cat("No kME stability results available.\n")

  } else {

    valid_kME <- is.finite(kME_stability$kME_correlation)

    if (any(valid_kME)) {

      values <- kME_stability$kME_correlation[valid_kME]

      cat(
        "Modules evaluated:     ",
        length(unique(kME_stability$Module[valid_kME])),
        "\n"
      )

      cat(
        "Median kME correlation:",
        round(stats::median(values), 3),
        "\n"
      )

      cat(
        "Range:                 ",
        paste(round(range(values), 3), collapse = " to "),
        "\n"
      )

    } else {

      cat("No valid kME correlations available.\n")
    }
  }
})

# Hub stability summary
.print_block("Hub Stability", function() {

  if (nrow(hub_stability) == 0) {

    cat("No hub stability results available.\n")

  } else {

    valid_hubs <- is.finite(hub_stability$Hub_Jaccard)

    if (any(valid_hubs)) {

      values <- hub_stability$Hub_Jaccard[valid_hubs]

      cat(
        "Modules evaluated:     ",
        length(unique(hub_stability$Module[valid_hubs])),
        "\n"
      )

      cat(
        "Median hub Jaccard:    ",
        round(stats::median(values), 3),
        "\n"
      )

      cat(
        "Median hub overlap:    ",
        round(stats::median(
          hub_stability$Hub_overlap[valid_hubs]
        ), 1),
        " shared hubs\n"
      )

      cat("\nModules with highest hub overlap:\n")

      hub_table <- hub_stability[
        valid_hubs,
        c(
          "Module",
          "Reference",
          "Comparison",
          "N_hubs",
          "Hub_overlap",
          "Hub_Jaccard"
        ),
        drop = FALSE
      ]

      hub_table <- hub_table[
        order(hub_table$Hub_Jaccard, decreasing = TRUE),
        ,
        drop = FALSE
      ]

      print(
        utils::head(hub_table, 10),
        row.names = FALSE
      )

    } else {

      cat("No valid hub stability results available.\n")
    }
  }
})

# =============================================================================
# 13. Attach result to project
# =============================================================================

if (save) {

  proj <- .attach_to_project(
    proj,
    obj,
    slot = "analyses",
    subtype = "wgcna_stability",
    log = list(
      reference = reference,
      comparison = comparison,
