# =============================================================================
# WGCNA module-trait analysis
# =============================================================================

#' Evaluate module-trait relationships in a WGCNA network
#'
#' @description
#'   Evaluates associations between module eigengenes and experimental groups
#'   using correlation analysis. The function uses module eigengenes obtained
#'   during WGCNA network construction to identify modules associated with a
#'   binary experimental condition.
#'
#'   Experimental groups are encoded as a binary trait, with the reference
#'   group represented by 0 and the comparison group by 1. Pearson correlation
#'   coefficients, corresponding p-values, and Benjamini-Hochberg adjusted
#'   p-values are calculated for each module.
#'
#'   Results include a module-trait association table and correlation matrix.
#'   An optional heatmap can be generated to visualize the direction and
#'   magnitude of module-trait relationships.
#'
#' @param project An \code{rna_project} object containing a previously
#'   constructed WGCNA network generated by \code{\link{rna_wgcna}}.
#'
#' @param group Optional character vector specifying the two experimental
#'   groups to compare. Both groups must be represented among the samples
#'   included in the original network. If \code{NULL}, groups are automatically
#'   identified when exactly two non-missing groups are available. Defaults
#'   to \code{NULL}.
#'
#' @param reference Optional character string specifying the reference group.
#'   The reference group is encoded as 0, whereas the other selected group is
#'   encoded as 1. If \code{NULL}, the first selected group is used. Defaults
#'   to \code{NULL}.
#'
#' @param plot Logical. If \code{TRUE}, generates a heatmap displaying
#'   module-trait correlation coefficients, with colors representing their
#'   direction and magnitude. Defaults to \code{TRUE}.
#'
#' @param save Logical. If \code{TRUE}, attaches the analysis result to the
#'   project under \code{analyses$wgcna_module_trait} and invisibly returns
#'   the updated project. Otherwise, invisibly returns an object of class
#'   \code{wgcna_module_trait_result}. Defaults to \code{TRUE}.
#'
#' @section Input requirements:
#'   The function requires a previously constructed WGCNA network containing
#'   module eigengenes. Sample metadata must contain the columns
#'   \code{Sample} and \code{Group}, with unique sample identifiers matching
#'   the row names of the module eigengene matrix.
#'
#'   Metadata are automatically aligned to the eigengene matrix, and samples
#'   outside the selected groups are excluded. Samples with missing group
#'   assignments or incomplete eigengene values are also excluded.
#'
#'   Both selected groups must contain at least one complete observation,
#'   with at least three complete samples available overall.
#'
#' @section Analysis:
#'   Module-trait relationships are evaluated using Pearson correlations
#'   between each module eigengene and the binary experimental trait.
#'   For binary traits, this is mathematically equivalent to a point-biserial
#'   correlation.
#'
#'   Positive correlations indicate higher eigengene values in the comparison
#'   group, whereas negative correlations indicate higher values in the
#'   reference group.
#'
#'   Statistical significance is estimated using the Student approximation
#'   implemented in \code{\link[WGCNA]{corPvalueStudent}}. P-values are
#'   adjusted across modules using the Benjamini-Hochberg procedure to control
#'   the false discovery rate (FDR).
#'
#'   Results are ranked by adjusted p-values, and the selected contrast is
#'   recorded in the resulting object.
#'
#' @section Interpretation:
#'   Correlation magnitude reflects the strength of the association between
#'   module eigengenes and the experimental condition. Statistical significance
#'   should be interpreted together with correlation magnitude, sample size,
#'   and adjusted p-values.
#'
#'   Module-trait associations identify modules whose expression patterns
#'   are associated with the selected condition, but do not establish causal
#'   relationships or demonstrate direct regulation of module genes.
#'
#' @section Scope and limitations:
#'   The function evaluates one binary contrast at a time and does not adjust
#'   for additional covariates, confounding factors, repeated measurements,
#'   or other sources of sample dependence.
#'
#'   The analysis uses module eigengenes calculated during network construction
#'   and does not identify differential co-expression or changes in network
#'   topology between experimental groups. Designs involving relevant
#'   covariates or complex sampling structures may require complementary
#'   regression or mixed-effects models.
#'
#' @return
#'   If \code{save = TRUE}, invisibly returns the updated \code{rna_project}
#'   object containing the module-trait analysis result.
#'
#'   If \code{save = FALSE}, invisibly returns an object of class
#'   \code{wgcna_module_trait_result}, containing:
#'   \itemize{
#'     \item \code{module_trait_results}: a data frame containing module
#'     identifiers, colors, selected groups, correlation coefficients,
#'     p-values, and FDR-adjusted p-values.
#'     \item \code{correlation}: a matrix of module-trait correlation
#'     coefficients.
#'     \item \code{pvalues}: a matrix of corresponding statistical p-values.
#'     \item \code{parameters}: a list containing selected groups,
#'     correlation settings, and sample counts.
#'     \item \code{timestamp}: date and time of analysis.
#'   }
#'
#' @seealso
#'   \code{\link{rna_wgcna}},
#'   \code{\link{rna_wgcna_metrics}},
#'   \code{\link[WGCNA]{corPvalueStudent}},
#'   \code{\link[WGCNA]{labeledHeatmap}}
#'
#' @references
#'   Langfelder P, Horvath S. (2008).
#'   WGCNA: an R package for weighted correlation network analysis.
#'   \emph{BMC Bioinformatics}, 9, 559.
#'   \doi{10.1186/1471-2105-9-559}
#'
#' @export


rna_wgcna_module_trait <- function(
    project,
    group = NULL,
    reference = NULL,
    plot = TRUE,
    save = TRUE
) {

# =============================================================================
# 0. Basic checks
# =============================================================================

.check_dependencies("WGCNA")

# project
if (!inherits(project, "rna_project")) {
  stop("`project` must be an object of class 'rna_project'.")
}

# group
if (!is.null(group)) {

  if (!is.character(group) ||
      length(group) != 2L ||
      anyNA(group) ||
      any(!nzchar(trimws(group))) ||
      anyDuplicated(group)) {

    stop(
      "`group` must contain exactly two distinct non-empty group names.",
      call. = FALSE
    )
  }
}

# reference
if (!is.null(reference)) {

  if (!is.character(reference) ||
      length(reference) != 1L ||
      is.na(reference) ||
      !nzchar(trimws(reference))) {

    stop(
      "`reference` must be a single non-empty character value.",
      call. = FALSE
    )
  }
}

# plot
if (!is.logical(plot) || length(plot) != 1L || is.na(plot)) {
  stop("`plot` must be TRUE or FALSE.")
}

# save
if (!is.logical(save) || length(save) != 1L || is.na(save)) {
  stop("`save` must be TRUE or FALSE.")
}

# =============================================================================
# 1. Get active project and WGCNA results
# =============================================================================

proj <- project

wgcna_obj <- .get_wgcna(proj)

if (!inherits(wgcna_obj, "wgcna_network_result")) {
  stop("Invalid WGCNA network result.", call. = FALSE)
}

MEs <- wgcna_obj$MEs

if (is.null(rownames(MEs)) || is.null(colnames(MEs))) {
  stop(
    "Module eigengenes must have sample and module identifiers.",
    call. = FALSE
  )
}

# =============================================================================
# 2. Retrieve and validate metadata
# =============================================================================

metadata <- .get_meta(proj)

if (!all(c("Sample", "Group") %in% colnames(metadata))) {
  stop(
    "Metadata must contain 'Sample' and 'Group' columns.",
    call. = FALSE
  )
}

if (anyDuplicated(metadata$Sample)) {
  stop(
    "Metadata contains duplicated sample identifiers.",
    call. = FALSE
  )
}

if (anyDuplicated(rownames(MEs))) {
  stop(
    "Module eigengenes contain duplicated sample identifiers.",
    call. = FALSE
  )
}

# Align metadata to module eigengenes
meta_idx <- match(rownames(MEs), as.character(metadata$Sample))

if (anyNA(meta_idx)) {
  stop(
    "Some WGCNA samples were not found in metadata.",
    call. = FALSE
  )
}

sample_groups <- as.character(metadata$Group[meta_idx])

available_groups <- unique(
  sample_groups[!is.na(sample_groups)]
)

if (length(available_groups) < 2L) {
  stop(
    "At least two experimental groups are required.",
    call. = FALSE
  )
}

# =============================================================================
# 3. Define group comparison
# =============================================================================

if (is.null(group)) {

  if (length(available_groups) != 2L) {
    stop(
      "Multiple groups detected. Please specify exactly two groups.",
      call. = FALSE
    )
  }

  group <- available_groups

} else {

  if (!all(group %in% available_groups)) {
    stop(
      "Some requested groups were not found in project metadata.",
      call. = FALSE
    )
  }
}

if (is.null(reference)) {
  reference <- group[1]
}

if (!reference %in% group) {
  stop(
    "`reference` must be one of the selected groups.",
    call. = FALSE
  )
}

comparison <- setdiff(group, reference)

# =============================================================================
# 4. Select samples and encode experimental groups
# =============================================================================

selected_samples <- !is.na(sample_groups) &
  sample_groups %in% group

MEs <- MEs[selected_samples, , drop = FALSE]

sample_groups <- sample_groups[selected_samples]

# Encode reference = 0 and comparison = 1
trait <- as.integer(sample_groups == comparison)

# Remove incomplete observations
complete_samples <- complete.cases(MEs) & !is.na(trait)

MEs <- MEs[complete_samples, , drop = FALSE]
trait <- trait[complete_samples]

if (length(unique(trait)) != 2L) {
  stop(
    "Both groups must have at least one complete observation.",
    call. = FALSE
  )
}

n_samples <- length(trait)

if (n_samples < 3L) {
  stop(
    "At least three complete samples are required.",
    call. = FALSE
  )
}

# =============================================================================
# 5. Calculate module-trait correlations
# =============================================================================

module_trait_correlation <- stats::cor(
  MEs,
  trait,
  method = "pearson"
)

module_trait_pvalues <- WGCNA::corPvalueStudent(
  module_trait_correlation,
  nSamples = n_samples
)

# =============================================================================
# 6. Organize module-trait results
# =============================================================================

module_trait_results <- data.frame(
  Module = rownames(module_trait_correlation),
  ModuleColor = sub(
    "^ME",
    "",
    rownames(module_trait_correlation)
  ),
  Reference = reference,
  Comparison = comparison,
  Correlation = as.numeric(module_trait_correlation),
  Pvalue = as.numeric(module_trait_pvalues),
  stringsAsFactors = FALSE
)

# Multiple testing correction
module_trait_results$FDR <- p.adjust(
  module_trait_results$Pvalue,
  method = "BH"
)

module_trait_results <- module_trait_results[
  order(module_trait_results$FDR),
  ,
  drop = FALSE
]

rownames(module_trait_results) <- NULL


# =============================================================================
# 7. Prepare correlation matrix
# =============================================================================

contrast_label <- paste(
  comparison,
  "vs",
  reference
)

colnames(module_trait_correlation) <- contrast_label

# =============================================================================
# 8. Diagnostic heatmap
# =============================================================================

if (plot) {

  WGCNA::labeledHeatmap(
    Matrix = module_trait_correlation,
    xLabels = contrast_label,
    yLabels = rownames(module_trait_correlation),
    colorLabels = FALSE,
    colors = WGCNA::blueWhiteRed(50),
    textMatrix = matrix(
      sprintf("%.2f", module_trait_correlation),
      nrow = nrow(module_trait_correlation),
      ncol = ncol(module_trait_correlation)
    ),
    zlim = c(-1, 1),
    legendWidth = 0.1,
    main = "Module-trait relationships"
  )
}

# =============================================================================
# 9. Build result object
# =============================================================================

obj <- list(
  module_trait_results = module_trait_results,
  correlation = module_trait_correlation,
  pvalues = module_trait_pvalues,
  parameters = list(
    reference = reference,
    comparison = comparison,
    cor_method = "pearson",
    n_samples = n_samples,
    n_reference = sum(trait == 0),
    n_comparison = sum(trait == 1)
  ),
  timestamp = Sys.time()
)

class(obj) <- "wgcna_module_trait_result"

# =============================================================================
# 10. Console summary
# =============================================================================

.print_header("WGCNA Module-Trait Results")

.print_block("Comparison Summary", function() {

  cat("Reference group:      ", reference, "\n")
  cat("Comparison group:     ", comparison, "\n")
  cat("Samples evaluated:    ", n_samples, "\n")
  cat("Reference samples:    ", sum(trait == 0), "\n")
  cat("Comparison samples:   ", sum(trait == 1), "\n")

})

.print_block("Correlation Summary", function() {

  significant <- sum(
    module_trait_results$FDR < 0.05,
    na.rm = TRUE
  )

  cat("Modules evaluated:    ", nrow(module_trait_results), "\n")
  cat("Significant modules:  ", significant, "\n")

})

.print_block("Module-Trait Associations", function() {

  print(
    module_trait_results[, c(
      "Module",
      "ModuleColor",
      "Correlation",
      "Pvalue",
      "FDR"
    )],
    row.names = FALSE
  )

})

# =============================================================================
# 11. Attach to project
# =============================================================================

if (save) {

  proj <- .attach_to_project(
    proj,
    obj,
    slot = "analyses",
    subtype = "wgcna_module_trait",
    log = list(
      reference = reference,
      comparison = comparison,
      n_samples = n_samples
    )
  )

  return(invisible(proj))
}

return(invisible(obj))

}
