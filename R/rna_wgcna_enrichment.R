# =============================================================================
# RNA WGCNA ENRICHMENT
# =============================================================================

#' Characterize WGCNA modules through functional enrichment analysis
#'
#' @description
#'   Performs gene set enrichment analysis (GSEA) to characterize the biological
#'   processes and molecular functions associated with WGCNA co-expression
#'   modules.
#'
#'   Genes are ranked according to their signed module membership (kME),
#'   calculated as the correlation between gene expression and the corresponding
#'   module eigengene. Enrichment analysis is performed independently for each
#'   selected module using the \code{\link[fgsea]{fgseaMultilevel}} algorithm.
#'
#'   Gene sets can be retrieved automatically from MSigDB or supplied by the
#'   user as a named list or GMT file. Gene identifiers are mapped to the
#'   identifiers used in the original WGCNA network before enrichment analysis.
#'
#' @param project An \code{rna_project} object containing a previously
#'   constructed WGCNA network generated by \code{\link{rna_wgcna}} and the
#'   corresponding gene annotation.
#'
#' @param modules Optional character vector specifying the WGCNA module colors
#'   to analyze. If \code{NULL}, all assigned modules are analyzed. Unassigned
#'   genes (grey modules) are excluded. Defaults to \code{NULL}.
#'
#' @param geneset_collection Character string specifying the MSigDB collection
#'   to retrieve when \code{pathways = NULL}. Common options include \code{"H"}
#'   (Hallmark), \code{"C2"} (curated gene sets), \code{"C5"}
#'   (ontology gene sets), \code{"C6"} (oncogenic signatures), \code{"C7"}
#'   (immunologic signatures), and \code{"C8"} (cellular signatures). Defaults
#'   to \code{"C5"}.
#'
#' @param geneset_subcollection Optional character string specifying the MSigDB
#'   subcollection. For example, \code{"GO:BP"} selects Gene Ontology Biological
#'   Process gene sets, while \code{"CP:REACTOME"} selects Reactome pathways.
#'   Some collections do not support subcollections. Defaults to \code{"GO:BP"}.
#'
#' @param pathways Optional collection of custom gene sets, supplied either as a
#'   named list of gene identifiers or as a path to a GMT file. If \code{NULL},
#'   gene sets are retrieved automatically from MSigDB according to
#'   \code{geneset_collection} and \code{geneset_subcollection}. Defaults to
#'   \code{NULL}.
#'
#' @param pathway_id_type Character string specifying the identifier type used
#'   in custom gene sets. Supported options are \code{"gene_id"},
#'   \code{"symbol"}, and \code{"entrez"}. This argument is ignored when MSigDB
#'   gene sets are retrieved automatically, as MSigDB gene symbols are used.
#'   Defaults to \code{"symbol"}.
#'
#' @param min_size Integer specifying the minimum number of mapped genes
#'   required for a gene set to be included in the enrichment analysis. Defaults
#'   to \code{10}.
#'
#' @param max_size Integer specifying the maximum number of mapped genes allowed
#'   for a gene set to be included in the enrichment analysis. Defaults to
#'   \code{500}.
#'
#' @param plot_top Integer specifying the maximum number of enriched pathways to
#'   visualize for each module. Pathways are selected according to their
#'   module-specific adjusted p-values (\code{padj_module}), regardless of
#'   statistical significance. Defaults to \code{5}.
#'
#' @param plot Logical. If \code{TRUE}, generates enrichment plots for the top
#'   pathways of each analyzed module using \code{\link[fgsea]{plotEnrichment}}.
#'   Defaults to \code{TRUE}.
#'
#' @param plot_dir Optional character string specifying the directory in which
#'   enrichment plots are saved as PDF files. The directory is created
#'   recursively if it does not exist. If \code{NULL}, plots are not saved to
#'   disk. Defaults to \code{NULL}.
#'
#' @param save Logical. If \code{TRUE}, attaches the analysis result to the
#'   project under \code{analyses$wgcna_enrichment} and invisibly returns the
#'   updated project. Otherwise, invisibly returns an object of class
#'   \code{wgcna_enrichment_result}. Defaults to \code{TRUE}.
#'
#' @section Input requirements:
#'   The project must contain a valid WGCNA result generated by
#'   \code{\link{rna_wgcna}}. The original result must include:
#'
#'   \itemize{
#'     \item An expression matrix with samples in rows and genes in columns.
#'     \item A gene-module assignment table containing gene identifiers, module
#'     labels, and module colors.
#'     \item Module eigengenes corresponding to the original expression matrix.
#'   }
#'
#'   When custom gene sets or MSigDB gene sets use symbols or Entrez
#'   identifiers, gene annotation must contain the corresponding identifiers and
#'   their mapping to the gene identifiers used in the WGCNA network.
#'
#'   Gene sets are mapped to the original network identifiers before analysis.
#'   Only mapped genes belonging to the original WGCNA network are retained.
#'   Gene sets are subsequently filtered according to their mapped sizes.
#'
#' @section Analysis:
#'   Enrichment analysis is performed independently for each selected module
#'   using the signed module membership (kME) as the ranking statistic.
#'
#'   kME is calculated as the correlation between each gene and the
#'   corresponding module eigengene, using the correlation method specified
#'   during the original WGCNA analysis.
#'
#'   For each module, genes are ranked in decreasing order of kME. The resulting
#'   rankings are analyzed using the multilevel GSEA algorithm implemented in
#'   \code{\link[fgsea]{fgseaMultilevel}}.
#'
#'   Two levels of multiple-testing correction are reported:
#'
#'   \itemize{
#'     \item \strong{Module-specific FDR (\code{padj_module}):}
#'     Benjamini-Hochberg adjusted p-values calculated independently within each
#'     module, considering all tested gene sets.
#'
#'     \item \strong{Global FDR (\code{padj_global}):}
#'     Benjamini-Hochberg adjusted p-values calculated across all
#'     module-by-pathway enrichment tests combined.
#'   }
#'
#'   Enrichment plots display the running enrichment score of selected gene sets
#'   along the ranked gene list. The top pathways are selected according to
#'   module-specific adjusted p-values, even when they do not reach the
#'   conventional significance threshold.
#'
#' @section Interpretation:
#'   Enrichment results characterize the functional composition of WGCNA modules
#'   and identify biological processes whose genes are concentrated toward one
#'   end of the module membership ranking.
#'
#'   The normalized enrichment score (NES) reflects the direction and magnitude
#'   of gene set enrichment relative to the signed kME ranking. Its sign
#'   indicates the direction of enrichment along that ranking, which depends on
#'   the orientation of the corresponding module eigengene.
#'
#'   Importantly, positive or negative NES values do not directly indicate
#'   biological pathway activation or inhibition. They describe the relative
#'   position of gene set members within the kME ranking and should be
#'   interpreted in the context of module eigengene orientation and gene
#'   expression patterns.
#'
#'   Enrichment results describe functional associations within co-expression
#'   modules and do not establish causal relationships, biochemical pathway
#'   activity, or functional activation of individual genes or cellular
#'   processes.
#'
#'   The analysis is based on the original WGCNA network and does not perform
#'   differential expression analysis, module-trait association testing,
#'   differential enrichment between experimental groups, or independent network
#'   reconstruction.
#'
#'   Statistical significance should be interpreted considering both
#'   module-specific and global FDR values, gene set size, annotation coverage,
#'   and the biological context of the analyzed modules.
#'
#' @return
#'   If \code{save = TRUE}, invisibly returns the updated
#'   \code{rna_project} object.
#'
#'   If \code{save = FALSE}, invisibly returns an object of class
#'   \code{wgcna_enrichment_result}, containing:
#'
#'   \itemize{
#'     \item \code{enrichment}: combined GSEA results for all analyzed
#'     module-by-pathway combinations, including enrichment scores, normalized
#'     enrichment scores, p-values, and adjusted p-values.
#'
#'     \item \code{kME}: matrix of gene-module membership correlations between
#'     all network genes and module eigengenes.
#'
#'     \item \code{rankings}: named list containing the signed kME rankings used
#'     for each analyzed module.
#'
#'     \item \code{gene_sets}: gene sets mapped to the identifiers used in the
#'     original WGCNA network and retained after size filtering.
#'
#'     \item \code{pathway_mapping}: summary of original and mapped gene set
#'     sizes, including pathway inclusion status.
#'
#'     \item \code{module_summary}: summary of the number of genes, tested
#'     pathways, and significant enrichment results for each module.
#'
#'     \item \code{plots}: nested list containing the enrichment plots generated
#'     for each module.
#'
#'     \item \code{parameters}: organism, gene set source, collection,
#'     identifier type, module selection, filtering thresholds, correlation
#'     method, and plotting configuration.
#'
#'     \item \code{data_summary}: summary of the number of genes, samples,
#'     modules, gene sets, and enrichment tests.
#'
#'     \item \code{timestamp}: date and time of analysis.
#'   }
#'
#' @seealso
#'   \code{\link{rna_wgcna}},
#'   \code{\link{rna_wgcna_metrics}},
#'   \code{\link{rna_wgcna_module_trait}},
#'   \code{\link{rna_wgcna_stability}},
#'   \code{\link[fgsea]{fgseaMultilevel}},
#'   \code{\link[fgsea]{plotEnrichment}},
#'   \code{\link[msigdbr]{msigdbr}}
#'
#' @references
#'   Subramanian A, Tamayo P, Mootha VK, et al. (2005).
#'   Gene set enrichment analysis: a knowledge-based approach for
#'   interpreting genome-wide expression profiles.
#'   \emph{Proceedings of the National Academy of Sciences},
#'   102(43), 15545--15550.
#'   \doi{10.1073/pnas.0506580102}
#'
#'   Korotkevich G, Sukhov V, Budin N, et al. (2021).
#'   Fast gene set enrichment analysis.
#'   bioRxiv.
#'   \doi{10.1101/060012}
#'
#'   Langfelder P, Horvath S. (2008).
#'   WGCNA: an R package for weighted correlation network analysis.
#'   \emph{BMC Bioinformatics}, 9, 559.
#'   \doi{10.1186/1471-2105-9-559}
#'
#' @export

rna_wgcna_enrichment <- function(
    project,
    modules = NULL,
    geneset_collection = "C5",
    geneset_subcollection = "GO:BP",
    pathways = NULL,
    pathway_id_type = "symbol",
    min_size = 10,
    max_size = 500,
    plot_top = 5,
    plot = TRUE,
    plot_dir = NULL,
    save = TRUE
) {

# =============================================================================
# 0. Basic checks
# =============================================================================

.check_dependencies("fgsea", bioc = TRUE)
.check_dependencies("BiocParallel", bioc = TRUE)

if (is.null(pathways)) {
  .check_dependencies("msigdbr")
}

if (plot) {
  .check_dependencies("ggplot2")
}

pathway_id_type <- match.arg(
  pathway_id_type,
  choices = c("gene_id", "symbol", "entrez")
)

# Validate numeric arguments
if (
  length(min_size) != 1 ||
  !is.numeric(min_size) ||
  !is.finite(min_size) ||
  min_size < 1
) {
  stop("`min_size` must be a positive integer.")
}

if (
  length(max_size) != 1 ||
  !is.numeric(max_size) ||
  !is.finite(max_size) ||
  max_size < min_size
) {
  stop("`max_size` must be greater than or equal to `min_size`.")
}

if (
  length(plot_top) != 1 ||
  !is.numeric(plot_top) ||
  !is.finite(plot_top) ||
  plot_top < 1
) {
  stop("`plot_top` must be a positive integer.")
}

min_size <- as.integer(min_size)
max_size <- as.integer(max_size)
plot_top <- as.integer(plot_top)

# =============================================================================
# 1. Get active project
# =============================================================================

proj <- project

organism <- .get_organism(proj)

message(
  "[rna_wgcna_enrichment] Using organism: ",
  organism
)

wgcna_obj <- .get_wgcna(proj)

if (!inherits(wgcna_obj, "wgcna_network_result")) {
  stop(
    "The current project does not contain a valid WGCNA network result."
  )
}

datExpr <- wgcna_obj$datExpr
genes_modules <- wgcna_obj$genes_modules
MEs <- wgcna_obj$MEs

# =============================================================================
# 2. Validate WGCNA object
# =============================================================================

if (
  is.null(datExpr) ||
  !is.matrix(datExpr) ||
  nrow(datExpr) < 2 ||
  ncol(datExpr) < 2
) {
  stop(
    "The stored WGCNA object does not contain a valid expression matrix."
  )
}

if (
  is.null(genes_modules) ||
  !is.data.frame(genes_modules)
) {
  stop(
    "The stored WGCNA object does not contain a valid gene-module table."
  )
}

required_columns <- c(
  "Gene",
  "Module",
  "ModuleColor"
)

missing_columns <- setdiff(
  required_columns,
  colnames(genes_modules)
)

if (length(missing_columns) > 0) {
  stop(
    "Missing columns in genes_modules: ",
    paste(missing_columns, collapse = ", ")
  )
}

if (
  is.null(MEs) ||
  !is.matrix(MEs) &&
  !is.data.frame(MEs)
) {
  stop(
    "The stored WGCNA object does not contain valid module eigengenes."
  )
}

MEs <- as.matrix(MEs)

network_genes <- colnames(datExpr)

if (
  is.null(network_genes) ||
  anyDuplicated(network_genes)
) {
  stop(
    "The expression matrix must contain unique gene identifiers."
  )
}

if (!all(genes_modules$Gene %in% network_genes)) {
  stop(
    "Gene identifiers in genes_modules do not match datExpr."
  )
}

if (
  nrow(MEs) != nrow(datExpr)
) {
  stop(
    "The number of samples in datExpr and MEs does not match."
  )
}

# Reorder MEs if sample names are available
if (
  !is.null(rownames(datExpr)) &&
  !is.null(rownames(MEs))
) {

  if (!setequal(rownames(datExpr), rownames(MEs))) {
    stop(
      "Sample identifiers in datExpr and MEs do not match."
    )
  }

  MEs <- MEs[
    match(rownames(datExpr), rownames(MEs)),
    ,
    drop = FALSE
  ]
}

# =============================================================================
# 3. Identify modules
# =============================================================================

module_info <- unique(
  genes_modules[, c("Module", "ModuleColor")]
)

module_info$Module <- as.character(
  module_info$Module
)

module_info$ModuleColor <- as.character(
  module_info$ModuleColor
)

# Remove unassigned genes
module_info <- module_info[
  !is.na(module_info$ModuleColor) &
    !module_info$ModuleColor %in% c("grey", "0"),
  ,
  drop = FALSE
]

if (nrow(module_info) == 0) {
  stop("No valid WGCNA modules were found.")
}

# Select modules
if (is.null(modules)) {

  selected_modules <- unique(
    module_info$ModuleColor
  )

} else {

  if (
    !is.character(modules) ||
    length(modules) == 0 ||
    anyNA(modules)
  ) {
    stop(
      "`modules` must be NULL or a character vector of module colors."
    )
  }

  selected_modules <- unique(modules)

  missing_modules <- setdiff(
    selected_modules,
    module_info$ModuleColor
  )

  if (length(missing_modules) > 0) {
    stop(
      "Unknown module(s): ",
      paste(missing_modules, collapse = ", "),
      ". Available modules: ",
      paste(
        unique(module_info$ModuleColor),
        collapse = ", "
      )
    )
  }

  module_info <- module_info[
    module_info$ModuleColor %in% selected_modules,
    ,
    drop = FALSE
  ]
}

message(
  "[rna_wgcna_enrichment] Modules selected: ",
  paste(selected_modules, collapse = ", ")
)

# =============================================================================
# 4. Load gene sets
# =============================================================================

pathway_source <- NULL

if (is.null(pathways)) {

  # ===============================================
  # 4.1. Load MSigDB
  # ===============================================

  geneset_collection <- toupper(
    geneset_collection
  )

  collections_without_sub <- c(
    "H", "C1", "C6", "C7", "C8"
  )

  if (
    geneset_collection %in% collections_without_sub &&
    !is.null(geneset_subcollection)
  ) {

    message(
      "[rna_wgcna_enrichment] Collection ",
      geneset_collection,
      " does not support subcollections. ",
      "Ignoring 'geneset_subcollection'."
    )

    geneset_subcollection <- NULL
  }

  species <- switch(
    organism,
    mouse = "Mus musculus",
    human = "Homo sapiens",
    zebrafish = "Danio rerio",
    stop(
      "Unsupported organism: ",
      organism,
      ". Supported organisms are human, mouse and zebrafish."
    )
  )

  # Compatibility check for zebrafish
  if (
    organism == "zebrafish" &&
    geneset_collection == "C5"
  ) {

    warning(
      "GO collections (C5) are not being used for zebrafish. ",
      "Switching to C2:REACTOME."
    )

    geneset_collection <- "C2"
    geneset_subcollection <- "CP:REACTOME"
  }

  if (geneset_collection %in% collections_without_sub) {

    msig <- msigdbr::msigdbr(
      species = species,
      collection = geneset_collection
    )

  } else {

    if (is.null(geneset_subcollection)) {
      stop(
        "A subcollection must be provided for collection ",
        geneset_collection,
        "."
      )
    }

    msig <- msigdbr::msigdbr(
      species = species,
      collection = geneset_collection,
      subcollection = geneset_subcollection
    )
  }

  if (
    is.null(msig) ||
    nrow(msig) == 0
  ) {
    stop(
      "No gene sets were retrieved from MSigDB."
    )
  }

  pathways <- split(
    as.character(msig$gene_symbol),
    as.character(msig$gs_name)
  )

  pathway_id_type_used <- "symbol"

  pathway_source <- paste0(
    "MSigDB:",
    geneset_collection,
    if (!is.null(geneset_subcollection)) {
      paste0(":", geneset_subcollection)
    } else {
      ""
    }
  )

} else {

  # ===============================================
  # 4.2. Custom gene sets
  # ===============================================

  if (inherits(pathways, "character") && length(pathways) == 1) {

    if (!file.exists(pathways)) {
      stop(
        "The provided GMT file does not exist: ",
        pathways
      )
    }

    pathways <- fgsea::gmtPathways(pathways)

  }

  if (
    !is.list(pathways) ||
    length(pathways) == 0 ||
    is.null(names(pathways)) ||
    anyNA(names(pathways)) ||
    any(names(pathways) == "")
  ) {
    stop(
      "`pathways` must be a named list of gene sets ",
      "or a valid GMT file path."
    )
  }

  pathway_id_type_used <- pathway_id_type
  pathway_source <- "Custom gene sets"

  message(
    "[rna_wgcna_enrichment] Using custom gene sets."
  )

}

# =============================================================================
# 5. Clean gene sets
# =============================================================================

# Convert all identifiers to character
pathways <- lapply(
  pathways,
  function(x) {

    if (
      !is.character(x) &&
      !is.numeric(x) &&
      !is.integer(x)
    ) {
      stop(
        "All gene sets must contain character or numeric identifiers."
      )
    }

    x <- as.character(x)

    x <- unique(
      x[!is.na(x) & x != ""]
    )

    x
  }
)

# Remove empty gene sets
pathways <- pathways[
  lengths(pathways) > 0
]

if (length(pathways) == 0) {
  stop("No valid gene sets remain after cleaning.")
}

# Preserve original pathway identifiers
pathway_ids <- names(pathways)

# =============================================================================
# 6. Map gene sets to WGCNA identifiers
# =============================================================================

# ===============================================
# 6.1. Gene annotation
# ===============================================

gene_map <- NULL

if (pathway_id_type_used != "gene_id") {

  gene_map <- .get_gene_annotation(proj)

  if (
    is.null(gene_map) ||
    !is.data.frame(gene_map)
  ) {
    stop(
      "Gene annotation is required to map gene sets ",
      "to WGCNA identifiers."
    )
  }

  required_annotation <- c(
    "gene_id",
    pathway_id_type_used
  )

  missing_annotation <- setdiff(
    required_annotation,
    colnames(gene_map)
  )

  if (length(missing_annotation) > 0) {
    stop(
      "Missing annotation columns: ",
      paste(missing_annotation, collapse = ", ")
    )
  }

  gene_map <- .align_gene_annotation(
    gene_map,
    t(datExpr)
  )

}

# ===============================================
# 6.2. Build identifier lookup
# ===============================================

if (pathway_id_type_used == "gene_id") {

  id_lookup <- list()

  id_lookup[network_genes] <- as.list(
    network_genes
  )

} else {

  gene_map <- gene_map[
    match(network_genes, gene_map$gene_id),
    ,
    drop = FALSE
  ]

  external_ids <- as.character(
    gene_map[[pathway_id_type_used]]
  )

  valid_mapping <- (
    !is.na(external_ids) &
      external_ids != "" &
      !is.na(gene_map$gene_id)
  )

  id_lookup <- split(
    as.character(gene_map$gene_id[valid_mapping]),
    external_ids[valid_mapping]
  )

}

# ===============================================
# 6.3. Convert pathways
# ===============================================

pathways_mapped <- lapply(
  pathways,
  function(ids) {

    ids <- unique(as.character(ids))

    mapped <- unlist(
      id_lookup[ids],
      use.names = FALSE
    )

    unique(
      mapped[
        !is.na(mapped) &
          mapped %in% network_genes
      ]
    )
  }
)

names(pathways_mapped) <- pathway_ids

# ===============================================
# 6.4. Pathway mapping summary
# ===============================================

pathway_mapping <- data.frame(
  pathway = pathway_ids,
  Original_size = lengths(pathways),
  Mapped_size = lengths(pathways_mapped),
  Included = (
    lengths(pathways_mapped) >= min_size &
      lengths(pathways_mapped) <= max_size
  ),
  stringsAsFactors = FALSE
)

# Filter gene sets by mapped size
pathways_mapped <- pathways_mapped[
  pathway_mapping$Included
]

if (length(pathways_mapped) == 0) {
  stop(
    "No gene sets passed the mapping and size filters. ",
    "Check gene identifiers and min_size/max_size."
  )
}

message(
  "[rna_wgcna_enrichment] Gene sets retained: ",
  length(pathways_mapped),
  " / ",
  length(pathways)
)

# =============================================================================
# 7. Calculate module membership (kME)
# =============================================================================

cor_method <- wgcna_obj$parameters$cor_method

if (is.null(cor_method)) {
  cor_method <- "pearson"
}

if (cor_method == "bicor") {

  kME <- WGCNA::bicor(
    datExpr,
    MEs,
    use = "pairwise.complete.obs"
  )

} else {

  kME <- stats::cor(
    datExpr,
    MEs,
    use = "pairwise.complete.obs",
    method = cor_method
  )

}

rownames(kME) <- network_genes

# =============================================================================
# 8. Run GSEA for each module
# =============================================================================

enrichment_list <- list()
rankings <- list()

for (i in seq_len(nrow(module_info))) {

  module_label <- module_info$Module[i]
  module_color <- module_info$ModuleColor[i]

  message(
    "[rna_wgcna_enrichment] Analyzing module ",
    module_color,
    " (",
    i,
    "/",
    nrow(module_info),
    ")"
  )

  # ===============================================
  # 8.1. Identify eigengene
  # ===============================================

  me_candidates <- unique(
    c(
      paste0("ME", module_color),
      paste0("ME", module_label)
    )
  )

  me_name <- me_candidates[
    me_candidates %in% colnames(kME)
  ][1]

  if (is.na(me_name)) {

    warning(
      "No eigengene found for module ",
      module_color,
      ". Skipping."
    )

    next
  }

  # ===============================================
  # 8.2. Extract module membership
  # ===============================================

  stats_vector <- kME[, me_name]

  names(stats_vector) <- rownames(kME)

  stats_vector <- stats_vector[
    is.finite(stats_vector)
  ]

  stats_vector <- sort(
    stats_vector,
    decreasing = TRUE
  )

  if (length(stats_vector) < min_size) {

    warning(
      "Not enough genes with valid kME values in module ",
      module_color,
      ". Skipping."
    )

    next
  }

  rankings[[module_color]] <- stats_vector

  # ===============================================
  # 8.3. GSEA
  # ===============================================

  gsea_res <- fgsea::fgseaMultilevel(
    pathways = pathways_mapped,
    stats = stats_vector,
    minSize = min_size,
    maxSize = max_size,
    eps = 0,
    BPPARAM = BiocParallel::SerialParam()
  )

  if (nrow(gsea_res) == 0) {
    next
  }

  gsea_res <- as.data.frame(gsea_res)

  gsea_res$Module <- module_color
  gsea_res$ModuleLabel <- module_label
  gsea_res$ME <- me_name

  gsea_res$padj_module <- gsea_res$padj

  enrichment_list[[module_color]] <- gsea_res

}

if (length(enrichment_list) == 0) {
  stop(
    "No enrichment results were generated. ",
    "Check module eigengenes, kME values and gene set compatibility."
  )
}

# =============================================================================
# 9. Combine enrichment results
# =============================================================================

enrichment <- do.call(
  rbind,
  enrichment_list
)

rownames(enrichment) <- NULL

# Global FDR across all module-pathway combinations
enrichment$padj_global <- stats::p.adjust(
  enrichment$pval,
  method = "BH"
)

# Clean pathway names for presentation
enrichment$pathway_name <- .smart_pathway_name(
  enrichment$pathway
)

# Order results
enrichment <- enrichment[
  order(
    enrichment$Module,
    enrichment$padj_module
  ),
  ,
  drop = FALSE
]

# =============================================================================
# 10. Module summary
# =============================================================================

module_summary <- do.call(
  rbind,
  lapply(names(rankings), function(module) {

    module_res <- enrichment[
      enrichment$Module == module,
      ,
      drop = FALSE
    ]

    data.frame(
      Module = module,
      N_genes = length(rankings[[module]]),
      N_pathways = nrow(module_res),
      N_significant_module = sum(
        module_res$padj_module < 0.05,
        na.rm = TRUE
      ),
      N_significant_global = sum(
        module_res$padj_global < 0.05,
        na.rm = TRUE
      ),
      stringsAsFactors = FALSE
    )

  })
)

rownames(module_summary) <- NULL

# =============================================================================
# 11. Enrichment plots
# =============================================================================

enrich_plots <- list()

if (plot) {

  if (!is.null(plot_dir)) {

    if (!dir.exists(plot_dir)) {
      dir.create(
        plot_dir,
        recursive = TRUE,
        showWarnings = FALSE
      )
    }

    if (!dir.exists(plot_dir)) {
      stop(
        "Could not create plot directory: ",
        plot_dir
      )
    }

  }

  for (module in names(rankings)) {

    module_res <- enrichment[
      enrichment$Module == module,
      ,
      drop = FALSE
    ]

    if (nrow(module_res) == 0) {
      next
    }

    module_res <- module_res[
      order(module_res$padj_module),
      ,
      drop = FALSE
    ]

    module_top <- utils::head(
      module_res,
      plot_top
    )

    module_plots <- lapply(
      seq_len(nrow(module_top)),
      function(i) {

        pathway_id <- module_top$pathway[i]

        pathway_label <- module_top$pathway_name[i]

        p <- fgsea::plotEnrichment(
          pathways_mapped[[pathway_id]],
          rankings[[module]]
        ) +
          ggplot2::labs(
            title = pathway_label,
            subtitle = paste0(
              "Module: ", module,
              " | NES = ", round(module_top$NES[i], 2),
              " | FDR = ", signif(module_top$padj_module[i], 3)
            ),
            x = "Ranked genes",
            y = "Enrichment score"
          ) +
          ggplot2::theme_classic(
            base_size = 12
          )

        # ===============================================
        # Save plot
        # ===============================================

        if (!is.null(plot_dir)) {

          safe_module <- gsub(
            "[^A-Za-z0-9_-]",
            "_",
            module
          )

          safe_pathway <- gsub(
            "[^A-Za-z0-9_-]",
            "_",
            pathway_id
          )

          filename <- paste0(
            "WGCNA_",
            safe_module,
            "_",
            safe_pathway,
            ".pdf"
          )

          ggplot2::ggsave(
            filename = file.path(
              plot_dir,
              filename
            ),
            plot = p,
            width = 4.5,
            height = 4
          )

        }

        p

      }
    )

    names(module_plots) <- module_top$pathway

    enrich_plots[[module]] <- module_plots

  }

  if (interactive()) {
    invisible(
      lapply(
        enrich_plots,
        function(x) {
          lapply(x, print)
        }
      )
    )
  }

}

