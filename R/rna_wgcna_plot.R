# =============================================================================
# WGCNA network visualization
# =============================================================================

#' Visualize WGCNA Module Networks
#'
#' @description
#'   Generates network visualizations from an existing WGCNA network, allowing
#'   the inspection of relationships between modules or the intramodular
#'   connectivity structure of an individual module.
#'
#'   Two visualization modes are available. The module network view represents
#'   relationships between module eigengenes using pairwise correlations,
#'   whereas the module detail view represents gene-level adjacency
#'   relationships within a selected module, highlighting highly
#'   connected hub genes.
#'
#'   The function uses the original WGCNA network and module assignments. It
#'   does not reconstruct the network, redefine modules, or recalculate module
#'   detection.
#'
#' @param project An \code{rna_project} object containing a previously
#'   constructed WGCNA network result, generated by \code{\link{rna_wgcna}}.
#'
#' @param view Character string specifying the visualization type.
#'   Available options are:
#'   \describe{
#'     \item{\code{"module_network"}}{
#'       Generates a network in which nodes represent modules and edges
#'       represent correlations between module eigengenes.
#'     }
#'     \item{\code{"module_detail"}}{
#'       Generates a gene-level network representing adjacency relationships
#'       within a selected module, with hub genes highlighted.
#'     }
#'   }
#'   Defaults to \code{"module_network"}.
#'
#' @param module Character string specifying the module to visualize when
#'   \code{view = "module_detail"}. Must match an existing module identifier
#'   in the WGCNA network. Unassigned genes (grey module) cannot be selected.
#'   Defaults to \code{NULL}.
#'
#' @param group Character string specifying the metadata group used for
#'   group-specific visualization. If \code{NULL}, the global network data are
#'   used. When a group is specified, the corresponding expression data and
#'   module eigengenes are used for the selected visualization, while the
#'   original global module assignments are retained. Defaults to \code{NULL}.
#'
#' @param edge_threshold Numeric value specifying the minimum edge strength
#'   required for an edge to be included in the visualization. Its
#'   interpretation depends on the selected view:
#'   \describe{
#'     \item{\code{"module_network"}}{
#'       Minimum absolute Pearson correlation between module eigengenes.
#'       Values range from greater than 0 to 1. Defaults to \code{0.30}.
#'     }
#'     \item{\code{"module_detail"}}{
#'       Minimum gene-to-gene adjacency value within the selected module.
#'       Values range from greater than 0 to 1. Defaults to \code{0.10}.
#'     }
#'   }
#'
#' @param hub_quantile Numeric value between 0 and 1 specifying the quantile
#'   used to identify hub genes in the \code{"module_detail"} view.
#'   Genes with intramodular connectivity (\code{kWithin}) at or above the
#'   corresponding quantile are classified as hub genes. Defaults to
#'   \code{0.90}.
#'
#' @param layout Character string specifying the graph layout algorithm used by
#'   \code{ggraph}. Common options include \code{"fr"} (Fruchterman-Reingold),
#'   \code{"kk"} (Kamada-Kawai), \code{"circle"}, \code{"dh"}, and
#'   \code{"stress"}. Defaults to \code{"fr"}.
#'
#' @param labels Logical. If \code{TRUE}, displays module identifiers in the
#'   \code{"module_network"} view and hub gene labels in the
#'   \code{"module_detail"} view. If \code{FALSE}, suppresses all node labels
#'   in both visualization modes. Defaults to \code{TRUE}.
#'
#' @param remove_isolated Logical. If \code{TRUE}, removes nodes without
#'   connections from the generated network visualization. If \code{FALSE},
#'   all nodes are retained, including isolated nodes. This argument applies
#'   to the \code{"module_network"} view. Defaults to \code{FALSE}.
#'
#' @param seed Optional integer used for reproducibility.
#'
#' @param plot Logical. If \code{TRUE}, prints the generated visualization.
#'   If \code{FALSE}, returns the visualization object without displaying the
#'   plot. Defaults to \code{TRUE}.
#'
#' @param save Logical. If \code{TRUE}, attaches the visualization result to the
#'   project under the \code{analyses} slot with subtype \code{"wgcna_plot"} and
#'   invisibly returns the updated project. If \code{FALSE}, does not attach the
#'   result and instead invisibly returns an object of class
#'   \code{wgcna_plot_result}. Defaults to \code{FALSE}.
#'
#' @details
#'   The module network view summarizes relationships between modules using
#'   Pearson correlations between their eigengenes. Each node represents a
#'   module, with node size proportional to the number of assigned genes. Edges
#'   represent pairwise eigengene correlations exceeding the selected absolute
#'   correlation threshold. Positive and negative correlations are visually
#'   distinguished.
#'
#'   The module detail view reconstructs the adjacency relationships between
#'   genes belonging to the selected module using the expression data available
#'   for the selected group. Gene connectivity is quantified using intramodular
#'   connectivity (\code{kWithin}), calculated as the sum of adjacency values
#'   connecting each gene to the other genes in the same module. Edges are
#'   retained according to the selected adjacency threshold.
#'
#'   Hub genes are identified from the distribution of intramodular connectivity
#'   values. The selected \code{hub_quantile} defines the minimum connectivity
#'   quantile used for hub classification. Hub genes are highlighted in the
#'   visualization and labeled using available gene symbols. When a gene symbol
#'   is unavailable, the corresponding gene identifier is used instead.
#'   Duplicated gene symbols are disambiguated using their original gene
#'   identifiers.
#'
#'   When group-specific visualization is requested, the original global module
#'   assignments are retained. However, eigengene correlations and gene-level
#'   adjacency relationships are evaluated using the expression data from the
#'   selected group. Consequently, differences between group-specific
#'   visualizations may reflect changes in expression relationships and
#'   connectivity patterns, as well as differences in sample size and expression
#'   variability.
#'
#'   These visualizations are intended for exploratory network inspection and
#'   biological interpretation. Correlations and adjacency values represent
#'   network relationships and should not be interpreted as evidence of direct
#'   molecular interactions, causal relationships, or statistically significant
#'   differences between groups.
#'
#'   The selected graph layout determines the spatial arrangement of nodes and
#'   does not represent biological distance or interaction strength
#'   independently of the network edges.
#'
#' @return
#'   If \code{save = TRUE}, invisibly returns the updated
#'   \code{rna_project} object.
#'
#'   If \code{save = FALSE}, invisibly returns an object of class
#'   \code{wgcna_plot_result}, containing:
#'   \describe{
#'     \item{plot}{The generated \code{ggraph}/\code{ggplot} visualization.
#'       May be \code{NULL} when \code{plot = FALSE}.}
#'     \item{graph}{An \code{igraph} object containing the network structure
#'       and associated node and edge attributes.}
#'     \item{nodes}{Data frame containing node-level information, including
#'       module assignments, module colors, gene identifiers, connectivity
#'       information, and visualization attributes. The exact columns depend
#'       on the selected view.}
#'     \item{edges}{Data frame containing the network edges and their associated
#'       correlation or adjacency attributes, depending on the selected view.}
#'     \item{correlation}{Matrix of pairwise module eigengene correlations for
#'       the \code{"module_network"} view. Returns \code{NULL} for the
#'       \code{"module_detail"} view.}
#'     \item{parameters}{List containing the selected visualization parameters,
#'       group information, sample count, network dimensions, edge threshold,
#'       layout, and hub identification settings when applicable.}
#'     \item{timestamp}{Date and time at which the visualization object
#'       was generated.}
#'   }
#'
#' @seealso
#'   \code{\link{rna_wgcna}},
#'   \code{\link{rna_wgcna_metrics}},
#'   \code{\link{rna_wgcna_stability}}
#'
#' @export

rna_wgcna_plot <- function(
    project,
    view = c("module_network", "module_detail"),
    module = NULL,
    group = NULL,
    edge_threshold = NULL,
    hub_quantile = 0.90,
    layout = c("fr", "kk", "circle", "dh", "stress"),
    labels = TRUE,
    remove_isolated = FALSE,
    seed = NULL,
    plot = TRUE,
    save = FALSE
) {

# =============================================================================
# 0. Basic checks
# =============================================================================

.check_dependencies("WGCNA")
.check_dependencies("igraph")
.check_dependencies("ggraph")
.check_dependencies("ggplot2")

# =============================================================================
# 1. Validade input
# =============================================================================

# Set seed
old_seed <- .set_seed(seed)
on.exit(.reset_seed(old_seed), add = TRUE)

# project
if (!inherits(project, "rna_project")) {
  stop("'project' must be an rna_project object.")
}

# view
view <- match.arg(view)

# module
if (view == "module_detail") {

if (is.null(module) ||
    !(is.character(module) || is.numeric(module)) ||
    length(module) != 1L ||
    is.na(module) ||
    !is.finite(if (is.numeric(module)) module else 1) ||
    !nzchar(trimws(as.character(module)))) {

  stop(
    "'module' must be a single non-empty module identifier ",
    "when view = 'module_detail'.",
    call. = FALSE
  )
}

module <- as.character(module)

}

# edge_threshold
if (is.null(edge_threshold)) {

  edge_threshold <- if (view == "module_network") {
    0.30
  } else {
    0.10
  }
}

if (!is.numeric(edge_threshold) ||
    length(edge_threshold) != 1L ||
    is.na(edge_threshold) ||
    !is.finite(edge_threshold) ||
    edge_threshold <= 0 ||
    edge_threshold > 1) {

  stop(
    "'edge_threshold' must be a finite numeric value ",
    "greater than 0 and less than or equal to 1.",
    call. = FALSE
  )
}

# hub_quantile
if (!is.numeric(hub_quantile) ||
    length(hub_quantile) != 1L ||
    is.na(hub_quantile) ||
    !is.finite(hub_quantile) ||
    hub_quantile < 0 ||
    hub_quantile > 1) {

  stop(
    "'hub_quantile' must be a finite numeric value ",
    "between 0 and 1.",
    call. = FALSE
  )
}

# layout
layout <- match.arg(layout)

# labels
if (!is.logical(labels) ||
    length(labels) != 1L ||
    is.na(labels)) {
  stop("'labels' must be TRUE or FALSE.", call. = FALSE)
}

# remove_isolated
if (!is.logical(remove_isolated) ||
    length(remove_isolated) != 1L ||
    is.na(remove_isolated)) {
  stop(
    "'remove_isolated' must be TRUE or FALSE.",
    call. = FALSE
  )
}

# plot
if (!is.logical(plot) ||
    length(plot) != 1L ||
    is.na(plot)) {
  stop("'plot' must be TRUE or FALSE.")
}

# Save
if (!is.logical(save) ||
    length(save) != 1L ||
    is.na(save)) {
  stop("'save' must be TRUE or FALSE.", call. = FALSE)
}

# =============================================================================
# 2. Get WGCNA results and group-specific data
# =============================================================================

proj <- project

wgcna_obj <- .get_wgcna(proj)

if (!inherits(wgcna_obj, "wgcna_network_result")) {
  stop("Invalid WGCNA network result.", call. = FALSE)
}

if (is.null(wgcna_obj$network)) {
  stop("WGCNA network information is missing.", call. = FALSE)
}

group_data <- .get_wgcna_group_data(
  project = proj,
  wgcna_obj = wgcna_obj,
  group = group
)

datExpr <- group_data$datExpr
MEs <- group_data$MEs

# =============================================================================
# 3. Build module network
# =============================================================================

ME_cor <- NULL
network_plot <- NULL

if (view == "module_network") {

  # =============================================
  # 3.1. Validate module eigengenes
  # =============================================

  if (is.null(MEs)) {
    stop(
      "Module eigengenes are required for 'module_network' view.",
      call. = FALSE
    )
  }

  MEs <- as.matrix(MEs)

  if (!is.numeric(MEs) ||
      is.null(rownames(MEs)) ||
      is.null(colnames(MEs))) {
    stop(
      "Module eigengenes must be a numeric matrix ",
      "with sample and module identifiers."
    )
  }

  if (ncol(MEs) < 2L || anyDuplicated(colnames(MEs))) {
    stop("At least two uniquely identified module eigengenes are required.")
  }

  # =============================================
  # 3.2. Retrieve and validate gene-module assignments
  # =============================================

  genes_modules <- wgcna_obj$genes_modules

  required_columns <- c(
    "Gene",
    "Module",
    "ModuleColor"
  )

  if (!is.data.frame(genes_modules) ||
      !all(required_columns %in% colnames(genes_modules))) {
    stop(
      "Gene-module assignments must contain 'Gene', ",
      "'Module' and 'ModuleColor' columns."
    )
  }

  if (anyNA(genes_modules$Module) ||
      anyNA(genes_modules$ModuleColor)) {
    stop("Gene-module assignments contain missing values.")
  }

  # =============================================
  # 3.3. Map eigengenes to module identifiers and colors
  # =============================================

  module_map <- unique(
    data.frame(
      module = as.character(genes_modules$Module),
      module_color = as.character(genes_modules$ModuleColor),
      stringsAsFactors = FALSE
    )
  )

  # Each module must have exactly one associated color
  color_counts <- table(module_map$module)

  if (any(color_counts > 1L)) {
    stop("Some modules are associated with multiple colors.")
  }

  # Extract module identifiers from eigengene names
  if (!all(startsWith(colnames(MEs), "ME"))) {
    stop(
      "Unexpected module eigengene names. ",
      "Expected identifiers starting with 'ME'."
    )
  }

  me_modules <- substring(colnames(MEs), 3L)

  # Match eigengenes to gene-module assignments
  module_idx <- match(
    me_modules,
    module_map$module
  )

  if (anyNA(module_idx)) {
    stop(
      "Some module eigengenes could not be matched ",
      "to the gene-module assignments."
    )
  }

  me_colors <- module_map$module_color[module_idx]

  # =============================================
  # 3.4. Select assigned modules and calculate module sizes
  # =============================================

  # Exclude unassigned genes (grey)
  valid_modules <- me_colors != "grey"

  MEs <- MEs[, valid_modules, drop = FALSE]

  module_ids <- me_modules[valid_modules]
  module_colors <- me_colors[valid_modules]

  if (length(module_ids) < 2L) {
    stop("At least two assigned modules are required.")
  }

  # Count genes per module
  module_sizes <- vapply(
    module_ids,
    function(x) {
      sum(as.character(genes_modules$Module) == x)
    },
    integer(1)
  )

  # =============================================
  # 3.5. Build module nodes
  # =============================================

  nodes <- data.frame(
    name = module_ids,
    module = module_ids,
    module_color = module_colors,
    n_genes = module_sizes,
    stringsAsFactors = FALSE
  )

  # =============================================
  # 3.6. Calculate eigengene correlations and build edges
  # =============================================

  # Use module identifiers as correlation matrix names
  colnames(MEs) <- module_ids

  # Calculate pairwise eigengene correlations
  ME_cor <- stats::cor(
    MEs,
    use = "pairwise.complete.obs",
    method = "pearson"
  )

  # Identify edges above the selected threshold
  edge_idx <- which(
    upper.tri(ME_cor) &
      is.finite(ME_cor) &
      abs(ME_cor) >= edge_threshold,
    arr.ind = TRUE
  )

  # Build edge table
  if (nrow(edge_idx) > 0L) {

    edges <- data.frame(
      from = module_ids[edge_idx[, 1]],
      to = module_ids[edge_idx[, 2]],
      correlation = ME_cor[edge_idx],
      abs_correlation = abs(ME_cor[edge_idx]),
      correlation_sign = ifelse(
        ME_cor[edge_idx] >= 0,
        "Positive",
        "Negative"
      ),
      stringsAsFactors = FALSE
    )

  } else {

    edges <- data.frame(
      from = character(),
      to = character(),
      correlation = numeric(),
      abs_correlation = numeric(),
      correlation_sign = character(),
      stringsAsFactors = FALSE
    )
  }

} else if (view == "module_detail") {

  module_data <- .calculate_wgcna_module_adjacency(
    wgcna_obj = wgcna_obj,
    module = module,
    edge_threshold = edge_threshold,
    datExpr = datExpr,
    hub_quantile = hub_quantile
  )

  nodes <- module_data$nodes
  edges <- module_data$edges

}

# =============================================================================
# 4. Remove isolated nodes
# =============================================================================

if (remove_isolated && nrow(edges) > 0L) {

  connected_nodes <- unique(c(
    edges$from,
    edges$to
  ))

  nodes <- nodes[
    nodes$name %in% connected_nodes,
    ,
    drop = FALSE
  ]

}

# =============================================================================
# 5. Add gene annotation
# =============================================================================

if (view == "module_detail") {

  gene_map <- .get_gene_annotation(proj)

  gene_map <- .align_gene_annotation(
    gene_map,
    t(wgcna_obj$datExpr)
  )

  gene_idx <- match(
    nodes$name,
    gene_map$gene_id
  )

  nodes$symbol <- gene_map$symbol[gene_idx]

  # Fallback to ENSEMBL when symbol is unavailable
  nodes$label <- ifelse(
    is.na(nodes$symbol) | nodes$symbol == "",
    nodes$name,
    nodes$symbol
  )

  # Handle duplicated symbols
  duplicated_symbols <- duplicated(nodes$label) |
    duplicated(nodes$label, fromLast = TRUE)

  nodes$label[duplicated_symbols] <- paste0(
    nodes$label[duplicated_symbols],
    " (",
    nodes$name[duplicated_symbols],
    ")"
  )

} else {

  nodes$label <- nodes$module

}

# Auxiliar color vector
nodes$module_border <- grDevices::adjustcolor(
  nodes$module_color,
  red.f = 0.65,
  green.f = 0.65,
  blue.f = 0.65
)

# =============================================================================
# 6. Construct graph
# =============================================================================

# Graph
graph <- igraph::graph_from_data_frame(
  d = edges,
  directed = FALSE,
  vertices = nodes
)

# =============================================================================
# 7. Generate visualization
# =============================================================================

if (view == "module_network") {

  network_plot <- ggraph::ggraph(
    graph,
    layout = layout
  ) +

  # ---------------------------------------------
  # 7.0.1. Edges
  # ---------------------------------------------

  ggraph::geom_edge_link(
    ggplot2::aes(
      edge_width = .data$abs_correlation,
      edge_colour = .data$correlation_sign
    ),
    alpha = 0.40,
    lineend = "round"
  ) +

    ggraph::scale_edge_width(
      range = c(0.2, 1.5),
      guide = "none"
    ) +

    ggraph::scale_edge_colour_manual(
      values = c(
        Positive = "#4C72B0",
        Negative = "#C44E52"
      ),
      name = "Correlation",
      drop = FALSE
    ) +

  # ---------------------------------------------
  # 7.0.2. Module nodes
  # ---------------------------------------------

  ggraph::geom_node_point(
    ggplot2::aes(
      size = .data$n_genes,
      fill = .data$module_color,
      color = .data$module_border
    ),
    shape = 21,
    stroke = 0.35,
    alpha = 0.90
  ) +

    ggplot2::scale_color_identity(guide = "none") +

    ggplot2::scale_fill_identity() +

    ggplot2::scale_size_area(
      max_size = 10,
      name = "Number of genes"
    )

  # ---------------------------------------------
  # 7.0.3. Module labels
  # ---------------------------------------------

  if (labels) {

    network_plot <- network_plot +
      ggraph::geom_node_text(
        ggplot2::aes(label = .data$module),
        size = 3,
        color = "grey20",
        fontface = "bold",
        vjust = 1.6
      )
  }

  # ---------------------------------------------
  # 7.0.4. Labels and theme
  # ---------------------------------------------

  network_plot <- network_plot +
    ggplot2::labs(
      title = paste0("Module network: ", group_data$group)
    ) +

    ggplot2::theme_void() +

    ggplot2::theme(
      plot.title = ggplot2::element_text(
        face = "bold",
        size = 12,
        color = "#263238"
      ),
      legend.position = "right",
      legend.title = ggplot2::element_text(
        size = 9,
        face = "bold"
      ),
      legend.text = ggplot2::element_text(
        size = 8
      ),
      plot.margin = ggplot2::margin(15, 15, 15, 15)
    )

# ===============================================
# 7.1. Module detail
# ===============================================

} else if (view == "module_detail") {

  network_plot <- ggraph::ggraph(
    graph,
    layout = layout
  ) +

  # ---------------------------------------------
  # 7.1.1. Edges
  # ---------------------------------------------

  ggraph::geom_edge_link(
    ggplot2::aes(edge_width = .data$adjacency),
    edge_colour = "grey65",
    alpha = 0.20,
    lineend = "round"
  ) +

    ggraph::scale_edge_width(
      range = c(0.1, 1.2),
      guide = "none"
    ) +

  # ---------------------------------------------
  # 7.1.2. Background genes
  # ---------------------------------------------

  ggraph::geom_node_point(
    ggplot2::aes(
      fill = .data$module_color,
      color = .data$module_border
    ),
    shape = 21,
    size = 2.2,
    stroke = 0.2,
    alpha = 0.65
  ) +

    ggplot2::scale_color_identity(guide = "none") +

  # ---------------------------------------------
  # 7.1.3. Hub genes
  # ---------------------------------------------

  ggraph::geom_node_point(
    ggplot2::aes(filter = .data$is_hub),
    shape = 21,
    fill = "#E69F00",
    color = "#754C00",
    size = 3.5,
    stroke = 0.7
  ) +

    ggplot2::scale_fill_identity()

  # ---------------------------------------------
  # 7.1.4. Hub labels
  # ---------------------------------------------

  if (labels) {

    network_plot <- network_plot +
      ggraph::geom_node_text(
        ggplot2::aes(
          filter = .data$is_hub,
          label = .data$label
        ),
        repel = TRUE,
        size = 3,
        color = "#263238",
        fontface = "bold",
        box.padding = 0.45,
        point.padding = 0.25,
        max.overlaps = Inf
      )
  }

  # ---------------------------------------------
  # 7.1.5. Labels and theme
  # ---------------------------------------------

  network_plot <- network_plot +
    ggplot2::labs(
      title = paste0(group_data$group, ": ", module, " module")
    ) +

    ggplot2::theme_void() +

    ggplot2::theme(
      plot.title = ggplot2::element_text(
        face = "bold",
        size = 12,
        color = "#263238"
      ),
      plot.margin = ggplot2::margin(20, 20, 20, 20)
    )
}

# =============================================================================
# 8. Visualization
# =============================================================================

if (plot) {
  print(network_plot)
}

# =============================================================================
# 9. RNG handling
# =============================================================================

rng_state <- if (exists(".Random.seed", envir = .GlobalEnv)) .Random.seed else NULL

seed <- if (is.null(seed)) {
  "not set"
} else {
  as.character(seed)
}

# =============================================================================
# 10. Build and return visualization object
# =============================================================================

obj <- list(
  plot = network_plot,
  graph = graph,
  nodes = nodes,
  edges = edges,
  correlation = ME_cor,

  parameters = list(
    view = view,
    module = if (view == "module_detail") module else NULL,
    group = group_data$group,
    n_samples = group_data$n_samples,
    edge_threshold = edge_threshold,
    layout = layout,
    n_nodes = nrow(nodes),
    n_edges = nrow(edges),
    gene_label = if (view == "module_detail") {
      "SYMBOL"
    } else {
      "MODULE"
    },
    hub_quantile = if (view == "module_detail") {
      module_data$hub_quantile
    } else {
      NULL
    },
    n_hubs = if (view == "module_detail") {
      module_data$n_hubs
    } else {
      NULL
    },
    seed = seed,
    rng_state = rng_state
  ),

  timestamp = Sys.time()
)

class(obj) <- "wgcna_plot_result"


# =============================================================================
# 11. Console summary
# =============================================================================

.print_header("WGCNA Plot Results")

.print_block("Visualization Summary", function() {

  cat("View:                  ", obj$parameters$view, "\n")
  cat("Group:                 ", obj$parameters$group, "\n")

  if (view == "module_detail") {
    cat("Module:                ", module, "\n")
  }

  cat("Samples used:          ", obj$parameters$n_samples, "\n")
  cat("Nodes:                 ", obj$parameters$n_nodes, "\n")
  cat("Edges:                 ", obj$parameters$n_edges, "\n")
  cat("Edge threshold:        ", obj$parameters$edge_threshold, "\n")
  cat("Layout:                ", obj$parameters$layout, "\n")

  if (view == "module_detail") {
    cat("Hub quantile:          ", obj$parameters$hub_quantile, "\n")
    cat("Hub genes:             ", obj$parameters$n_hubs, "\n")
  }

})

# =============================================================================
# 12. Attach to project
# =============================================================================

if (save) {

  proj <- .attach_to_project(
    proj,
    obj,
    slot = "analyses",
    subtype = "wgcna_plot",
    log = list(
      view = view,
      module = if (view == "module_detail") module else NULL,
      group = group_data$group,
      n_nodes = obj$parameters$n_nodes,
      n_edges = obj$parameters$n_edges,
      edge_threshold = edge_threshold,
      layout = layout,
      hub_quantile = if (view == "module_detail") {
        obj$parameters$hub_quantile
      } else {
        NULL
      },
      seed = seed
    )
  )

  return(invisible(proj))
}

return(invisible(obj))

}
